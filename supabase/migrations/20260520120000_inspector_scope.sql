-- Inspector lines: main row + members (profile_id = bookers this line manages)

CREATE TABLE IF NOT EXISTS public."Inspector" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inspector_name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT inspector_name_unique UNIQUE (inspector_name)
);

CREATE TABLE IF NOT EXISTS public."Inspector_Member" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inspector_id bigint NOT NULL REFERENCES public."Inspector" (id) ON DELETE CASCADE,
  profile_id uuid NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT inspector_member_unique UNIQUE (inspector_id, profile_id)
);

CREATE INDEX IF NOT EXISTS inspector_member_inspector_id_idx ON public."Inspector_Member" (inspector_id);
CREATE INDEX IF NOT EXISTS inspector_member_profile_id_idx ON public."Inspector_Member" (profile_id);

ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS inspector_id bigint REFERENCES public."Inspector" (id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS profiles_inspector_id_idx ON public.profiles (inspector_id);

-- Helpers for RLS / app
CREATE OR REPLACE FUNCTION public.is_app_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id = auth.uid() AND p.role = 'admin'
  );
$$;

CREATE OR REPLACE FUNCTION public.inspector_scope_includes_booker(p_booked_by uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT p_booked_by IS NOT NULL
    AND EXISTS (
      SELECT 1
      FROM public.profiles mgr
      INNER JOIN public."Inspector_Member" im ON im.inspector_id = mgr.inspector_id
      WHERE mgr.id = auth.uid()
        AND mgr.role = 'manager'
        AND mgr.inspector_id IS NOT NULL
        AND im.profile_id = p_booked_by
    );
$$;

GRANT EXECUTE ON FUNCTION public.is_app_admin() TO authenticated;
GRANT EXECUTE ON FUNCTION public.inspector_scope_includes_booker(uuid) TO authenticated;

ALTER TABLE public."Inspector" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."Inspector_Member" ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS inspector_select_authenticated ON public."Inspector";
CREATE POLICY inspector_select_authenticated ON public."Inspector"
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS inspector_admin_write ON public."Inspector";
CREATE POLICY inspector_admin_write ON public."Inspector"
  FOR ALL TO authenticated
  USING (public.is_app_admin())
  WITH CHECK (public.is_app_admin());

DROP POLICY IF EXISTS inspector_member_select_authenticated ON public."Inspector_Member";
CREATE POLICY inspector_member_select_authenticated ON public."Inspector_Member"
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS inspector_member_admin_write ON public."Inspector_Member";
CREATE POLICY inspector_member_admin_write ON public."Inspector_Member"
  FOR ALL TO authenticated
  USING (public.is_app_admin())
  WITH CHECK (public.is_app_admin());

-- Request: managers in scope may read/update (additive PERMISSIVE policies)
DROP POLICY IF EXISTS request_manager_select_in_inspector_scope ON public."Request";
CREATE POLICY request_manager_select_in_inspector_scope ON public."Request"
  FOR SELECT TO authenticated
  USING (public.inspector_scope_includes_booker(booked_by));

DROP POLICY IF EXISTS request_manager_update_in_inspector_scope ON public."Request";
CREATE POLICY request_manager_update_in_inspector_scope ON public."Request"
  FOR UPDATE TO authenticated
  USING (public.inspector_scope_includes_booker(booked_by))
  WITH CHECK (public.inspector_scope_includes_booker(booked_by));
